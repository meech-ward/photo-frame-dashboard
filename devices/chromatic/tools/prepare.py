def tls_heap_config(config):
    # Joined Realtime plus a snapshot HTTPS request drove measured free heap
    # to 104 bytes. IDF's dynamic records release idle RX/TX storage while
    # retaining the 16 KiB receive limit needed by ordinary hosted servers.
    # Verification still completes normally; the peer certificate is then
    # dispensable. Keep the bundle/config attached for later TLS handshakes.
    settings = {
        "MBEDTLS_DYNAMIC_BUFFER": "y",
        "MBEDTLS_SSL_KEEP_PEER_CERTIFICATE": None,
        "MBEDTLS_DYNAMIC_FREE_CONFIG_DATA": None,
        "MBEDTLS_DYNAMIC_FREE_CA_CERT": None,
    }
    for symbol, value in settings.items():
        line = f"CONFIG_{symbol}={value}" if value else f"# CONFIG_{symbol} is not set"
        pattern = rf"(?m)^(?:CONFIG_{symbol}=.*|# CONFIG_{symbol} is not set)$"
        config, count = re.subn(pattern, line, config)
        if not count:
            config += "\n" + line + "\n"
    return config


def generate(target, home):
    from PIL import Image, ImageOps
    data = json.loads((home / "fixtures/demo.json").read_text())
    wire = json.dumps(data, separators=(",", ":"), ensure_ascii=False)
    (target / "homehq_demo.c").write_text(
        '#include "homehq.h"\n/* Shared authored fixture; generated by prepare.py. */\n'
        'const char homehq_demo_json[] = ' + json.dumps(wire) + ';\n')
    lines = ['#include "homehq.h"', '/* Native-size offline samples need no decode heap. */']
    for key in ("coast", "lake", "mountain"):
        image = Image.open(home / f"devices/badge/assets/photo-{key}.png").convert("RGB")
        # Match downloaded photos: preserve the badge artwork's 4:3 aspect
        # ratio inside the wider native card, rather than stretching faces.
        scaled = ImageOps.contain(image, (128, 72), Image.Resampling.LANCZOS)
        image = Image.new("RGB", (128, 72), (242, 238, 230))
        image.paste(scaled, ((128-scaled.width)//2, (72-scaled.height)//2))
        pixels = []
        for red, green, blue in image.getdata():
            word = ((red >> 3) << 11) | ((green >> 2) << 5) | (blue >> 3)
            pixels.extend((word & 255, word >> 8))
        lines.append(f"static const uint8_t {key}_pixels[] = {{")
        lines.extend(" " + ",".join(map(str, pixels[i:i+48])) + "," for i in range(0, len(pixels), 48))
        lines.extend(("};", f"const lv_img_dsc_t homehq_photo_{key} = {{.header = {{.cf = LV_IMG_CF_TRUE_COLOR, .w = 128, .h = 72}}, .data_size = sizeof({key}_pixels), .data = {key}_pixels}};"))
    (target / "homehq_assets.c").write_text("\n".join(lines) + "\n")


